# ---------------------------------------------------------------------------
# Вспомогательные функции интерполяции
# ---------------------------------------------------------------------------

def _interp_table(table: dict, key: float) -> dict:
    """Линейная интерполяция словаря {глубина: значения} по ключу (глубина)."""
    keys = sorted(table.keys())
    if key <= keys[0]:
        return table[keys[0]]
    if key >= keys[-1]:
        return table[keys[-1]]
    for i in range(len(keys) - 1):
        k1, k2 = keys[i], keys[i + 1]
        if k1 <= key <= k2:
            t = (key - k1) / (k2 - k1)
            v1, v2 = table[k1], table[k2]
            # интерполируем все подзначения
            result = {}
            for sub_key in v1:
                result[sub_key] = v1[sub_key] + t * (v2[sub_key] - v1[sub_key])
            return result
    return table[keys[-1]]


def _interp_depth_value(table: dict, depth: float, sub_key) -> float:
    """Интерполирует значение из таблицы {глубина: {sub_key: float}} по глубине и sub_key."""
    interpolated = _interp_table(table, depth)
    sub_keys = sorted(interpolated.keys())
    if sub_key in interpolated:
        return interpolated[sub_key]
    # Если sub_key не строка (числовой IL) — интерполируем
    if isinstance(sub_key, (int, float)):
        if sub_key <= sub_keys[0]:
            return interpolated[sub_keys[0]]
        if sub_key >= sub_keys[-1]:
            return interpolated[sub_keys[-1]]
        for i in range(len(sub_keys) - 1):
            k1, k2 = sub_keys[i], sub_keys[i + 1]
            if k1 <= sub_key <= k2:
                t = (sub_key - k1) / (k2 - k1)
                return interpolated[k1] + t * (interpolated[k2] - interpolated[k1])
    return 0.0


def _interp_depth_only(table: dict, depth: float, sub_key) -> float:
    """Для таблицы {глубина: R_кПа} (только одно значение на глубину)."""
    keys = sorted(table.keys())
    if depth <= keys[0]:
        return table[keys[0]]
    if depth >= keys[-1]:
        return table[keys[-1]]
    for i in range(len(keys) - 1):
        k1, k2 = keys[i], keys[i + 1]
        if k1 <= depth <= k2:
            t = (depth - k1) / (k2 - k1)
            return table[k1] + t * (table[k2] - table[k1])
    return table[keys[-1]]


# ---------------------------------------------------------------------------
# Выбор нужного IL-ключа для таблицы R (по граничным значениям 0.0 / 0.5 / 1.0)
# ---------------------------------------------------------------------------

def _il_key_for_R(il: Optional[float]) -> float:
    """Возвращает ближайший ключ IL из таблицы R для глинистых (0.0, 0.5, 1.0)."""
    if il is None or il <= 0.0:
        return 0.0
    elif il <= 0.5:
        return 0.5
    else:
        return 1.0


# ---------------------------------------------------------------------------
# Получение R (сопротивление под нижним концом) для конкретного слоя
# ---------------------------------------------------------------------------

def get_R(soil_type: str, sand_fraction: Optional[str],
          il: Optional[float], depth_tip: float, pile_type: str) -> float:
    """
    Расчётное сопротивление грунта под нижним концом сваи R, кПа.
    По таблице 7.2 СП 24.13330.2021.

    :param soil_type:     Вид грунта ('Песок', 'Супесь', 'Суглинок', 'Глина', 'Насыпной', 'Торф')
    :param sand_fraction: Крупность для песков
    :param il:            Показатель текучести для глинистых
    :param depth_tip:     Глубина нижнего конца сваи от поверхности земли, м
    :param pile_type:     'Забивная' | 'Вдавливаемая' | 'Вибропогружение' | 'Буронабивная'
    :return: R, кПа
    """
    is_bored = (pile_type == "Буронабивная")

    if soil_type == "Песок":
        fraction = sand_fraction or "Мелкий"
        table = _R_BORED_SAND if is_bored else _R_DRIVEN_SAND
        depth_table = table.get(fraction, table["Мелкий"])
        return _interp_depth_only(depth_table, depth_tip, None)

    elif soil_type in ("Супесь", "Суглинок", "Глина"):
        table = _R_BORED_CLAY if is_bored else _R_DRIVEN_CLAY
        il_key = _il_key_for_R(il)
        depth_table = table[il_key]
        return _interp_depth_only(depth_table, depth_tip, None)

    else:
        # Насыпной, Торф и прочие — несущая способность не определяется
        return 0.0


# ---------------------------------------------------------------------------
# Получение fi (сопротивление по боковой поверхности) для одного подслоя
# ---------------------------------------------------------------------------

def get_fi(soil_type: str, sand_fraction: Optional[str],
           il: Optional[float], depth_mid: float, pile_type: str) -> float:
    """
    Расчётное сопротивление i-го слоя грунта по боковой поверхности сваи fi, кПа.
    По таблице 7.3 СП 24.13330.2021.

    :param soil_type:     Вид грунта
    :param sand_fraction: Крупность для песков
    :param il:            Показатель текучести для глинистых
    :param depth_mid:     Глубина середины подслоя от поверхности земли, м
    :param pile_type:     Тип сваи
    :return: fi, кПа
    """
    is_bored = (pile_type == "Буронабивная")

    if soil_type == "Песок":
        fraction = sand_fraction or "Мелкий"
        table = _F_BORED_SAND if is_bored else _F_DRIVEN_SAND
        return _interp_depth_value(table, depth_mid, fraction)

    elif soil_type in ("Супесь", "Суглинок", "Глина"):
        table = _F_BORED_CLAY if is_bored else _F_DRIVEN_CLAY
        il_val = il if il is not None else 0.5
        # IL ограничиваем диапазоном [0; 1]
        il_val = max(0.0, min(1.0, il_val))
        return _interp_depth_value(table, depth_mid, il_val)

    else:
        # Насыпной, Торф — не учитываем по боковой поверхности
        return 0.0


# ---------------------------------------------------------------------------
# Разбивка пласта на подслои ≤ 2 м (требование СП 24 п. 7.2)
# ---------------------------------------------------------------------------

def split_layer_to_sublayers(depth_top: float, depth_bottom: float,
                             max_h: float = 2.0) -> list:
    """
    Разбивает пласт [depth_top, depth_bottom] на подслои не более max_h м.
    Возвращает список (h, depth_mid).
    """
    sublayers = []
    current = depth_top
    total = depth_bottom - depth_top
    if total <= 0:
        return sublayers
    while current < depth_bottom - 1e-9:
        end = min(current + max_h, depth_bottom)
        h = end - current
        mid = (current + end) / 2.0
        sublayers.append((h, mid))
        current = end
    return sublayers


# ---------------------------------------------------------------------------
# Коэффициенты условий работы (γc, γcR, γcf) по СП 24 таблица 3
# ---------------------------------------------------------------------------

def get_gammas(pile_type: str) -> tuple:
    """
    Возвращает (γc, γcR, γcf) для данного типа сваи.
    γc  — общий коэф. условий работы
    γcR — коэф. условий работы грунта под острием
    γcf — коэф. условий работы грунта по боковой поверхности
    """
    if pile_type in ("Забивная", "Вдавливаемая", "Вибропогружение"):
        return 1.0, 1.0, 1.0
    elif pile_type == "Буронабивная":
        return 1.0, 0.9, 0.6  # уже учтены в таблицах _R_BORED / _F_BORED
    else:
        return 1.0, 1.0, 1.0


# ---------------------------------------------------------------------------
# Главная функция расчёта
# ---------------------------------------------------------------------------

def calc_sp24(pile_type: str, length: float, diameter: float,
              head_z: float, bh_z_collar: float,
              layers: list) -> dict:
    """
    Расчёт несущей способности сваи по грунту (аналитический метод, п. 7.2 СП 24).

    :param pile_type:    Тип сваи ('Забивная', 'Вдавливаемая', 'Вибропогружение', 'Буронабивная')
    :param length:       Длина ствола сваи, м
    :param diameter:     Диаметр/сечение сваи, м
    :param head_z:       Абсолютная отметка оголовка, м
    :param bh_z_collar:  Абсолютная отметка устья скважины, м
    :param layers:       Список слоёв скважины (dict с ключами из soil_layers)
    :return: Словарь с результатами расчёта:
        {
          'Fd': float,          # Несущая способность по грунту, кН
          'R_tip': float,       # Сопротивление грунта под острием, кН
          'F_lateral': float,   # Суммарное боковое сопротивление, кН
          'A': float,           # Площадь сечения у острия, м²
          'u': float,           # Периметр сваи, м
          'depth_tip': float,   # Глубина нижнего конца от устья скважины, м
          'z_tip': float,       # Абсолютная отметка нижнего конца, м
          'sublayers': list,    # Список подслоёв с fi, hi, результатами
          'tip_layer': dict,    # Слой под нижним концом сваи
          'warnings': list,     # Предупреждения
          'pile_type': str,
          'gammas': tuple,
        }
    """
    import math

    warnings = []

    # Геометрия
    A = math.pi * diameter ** 2 / 4.0  # круглое сечение (для квадратного пользователь вводит эквивалентный d)
    u = math.pi * diameter

    gamma_c, gamma_cR, gamma_cf = get_gammas(pile_type)

    # Отметка нижнего конца (острия)
    z_tip = head_z - length
    # Глубина нижнего конца от устья скважины
    depth_tip = bh_z_collar - z_tip

    if depth_tip <= 0:
        warnings.append("⚠️ Нижний конец сваи выше устья скважины — проверьте отметку оголовка и длину!")
        depth_tip = 0.01

    # Отметка оголовка относительно поверхности земли (устья скважины)
    # Верхняя граница ствола, участвующего в боковом трении:
    z_head = head_z
    z_bottom_pile = z_tip

    # Верхняя граница ствола ≤ поверхность земли (сваи, забитые ниже поверхности)
    z_top_friction = min(z_head, bh_z_collar)
    depth_top_friction = bh_z_collar - z_top_friction  # = max(0, bh_z_collar - z_head)

    # --- Поиск слоя под нижним концом ---
    tip_layer = None
    sorted_layers = sorted(layers, key=lambda l: l['depth_top'])
    for lyr in sorted_layers:
        if lyr['depth_top'] <= depth_tip <= lyr['depth_bottom']:
            tip_layer = lyr
            break
    if tip_layer is None and sorted_layers:
        # Если острие ниже всех слоёв — берём последний
        tip_layer = sorted_layers[-1]
        warnings.append(
            f"⚠️ Нижний конец сваи ({depth_tip:.2f} м) ниже описанных слоёв скважины. "
            f"R принят по последнему слою '{tip_layer['soil_type']}'."
        )

    if tip_layer is None:
        warnings.append("❌ Не найдены слои скважины для расчёта!")
        return {
            'Fd': 0.0, 'R_tip': 0.0, 'F_lateral': 0.0,
            'A': A, 'u': u, 'depth_tip': depth_tip, 'z_tip': z_tip,
            'sublayers': [], 'tip_layer': None, 'warnings': warnings,
            'pile_type': pile_type, 'gammas': (gamma_c, gamma_cR, gamma_cf)
        }

    # --- R под нижним концом ---
    R = get_R(
        soil_type=tip_layer['soil_type'],
        sand_fraction=tip_layer.get('sand_fraction'),
        il=tip_layer.get('il'),
        depth_tip=depth_tip,
        pile_type=pile_type
    )
    if R == 0.0:
        warnings.append(
            f"⚠️ Грунт под нижним концом ('{tip_layer['soil_type']}') не учитывается в несущей способности "
            f"(насыпной, торф и т.п.)"
        )

    R_tip_kN = gamma_c * gamma_cR * R * A  # кН

    # --- Боковое трение — послойный расчёт ---
    sublayer_results = []
    sum_fi_hi = 0.0

    for lyr in sorted_layers:
        # Определяем пересечение слоя с активной зоной ствола
        # (от глубины верхней границы трения до нижнего конца сваи)
        active_top = max(lyr['depth_top'], depth_top_friction)
        active_bot = min(lyr['depth_bottom'], depth_tip)

        if active_bot <= active_top:
            continue  # слой не пересекается со стволом

        # Разбиваем на подслои ≤ 2 м
        sublayers = split_layer_to_sublayers(active_top, active_bot, max_h=2.0)
        for (h, depth_mid) in sublayers:
            fi = get_fi(
                soil_type=lyr['soil_type'],
                sand_fraction=lyr.get('sand_fraction'),
                il=lyr.get('il'),
                depth_mid=depth_mid,
                pile_type=pile_type
            )
            fi_hi = fi * h
            sum_fi_hi += fi_hi
            sublayer_results.append({
                'ige_code': lyr.get('ige_code', ''),
                'soil_type': lyr['soil_type'],
                'sand_fraction': lyr.get('sand_fraction', ''),
                'il': lyr.get('il'),
                'consistency': lyr.get('consistency', ''),
                'depth_top_sub': round(active_top, 2),
                'depth_bot_sub': round(active_bot, 2),
                'h': round(h, 2),
                'depth_mid': round(depth_mid, 2),
                'fi': round(fi, 2),
                'fi_hi': round(fi_hi, 2),
            })

    F_lateral_kN = gamma_c * gamma_cf * u * sum_fi_hi

    Fd = R_tip_kN + F_lateral_kN

    return {
        'Fd': round(Fd, 1),
        'R_tip': round(R_tip_kN, 1),
        'F_lateral': round(F_lateral_kN, 1),
        'R_kPa': round(R, 1),
        'A': round(A, 4),
        'u': round(u, 4),
        'depth_tip': round(depth_tip, 2),
        'z_tip': round(z_tip, 2),
        'sublayers': sublayer_results,
        'tip_layer': tip_layer,
        'warnings': warnings,
        'pile_type': pile_type,
        'gammas': (gamma_c, gamma_cR, gamma_cf),
        'gamma_c': gamma_c,
        'gamma_cR': gamma_cR,
        'gamma_cf': gamma_cf,
    }
